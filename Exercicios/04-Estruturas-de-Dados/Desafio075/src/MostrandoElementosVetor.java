// Criar um vetor com 10 números inteiros e mostre todos os elementos utilizando um for.

public class MostrandoElementosVetor {

    public static void main(String[] args){
        int numeros[] = {5, 4, 6, 7, 2, 1, 8, 9, 10, 22};

        for (int valor: numeros){
            System.out.println(valor);
        }
    }
}
